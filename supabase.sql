
-- Supabase SQL Editor で実行
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  role text not null default 'viewer' check (role in ('admin','viewer')),
  disabled boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.records (
  id bigint generated by default as identity primary key,
  title text not null,
  category text not null default '',
  note text not null default '',
  completed boolean not null default false,
  created_by uuid references auth.users(id),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.records enable row level security;

create or replace function public.is_active_user()
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and disabled = false
  );
$$;

create or replace function public.is_admin()
returns boolean language sql stable security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and role = 'admin' and disabled = false
  );
$$;

drop policy if exists "read own profile" on public.profiles;
create policy "read own profile" on public.profiles
for select to authenticated using (id = auth.uid());

drop policy if exists "active users read records" on public.records;
create policy "active users read records" on public.records
for select to authenticated using (public.is_active_user());

drop policy if exists "admins insert records" on public.records;
create policy "admins insert records" on public.records
for insert to authenticated with check (public.is_admin());

drop policy if exists "admins update records" on public.records;
create policy "admins update records" on public.records
for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admins delete records" on public.records;
create policy "admins delete records" on public.records
for delete to authenticated using (public.is_admin());

grant select on public.profiles to authenticated;
grant select, insert, update, delete on public.records to authenticated;
grant usage, select on sequence public.records_id_seq to authenticated;

